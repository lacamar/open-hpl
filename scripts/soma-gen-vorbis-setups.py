#!/usr/bin/env python3
"""Regenerate soma/src/game/SomaVorbisSetups.h for the setup crcs the installed games use.

Usage: soma-gen-vorbis-setups.py <python-fsb5 fsb5/vorbis_headers.py>   (read as data, never run)
"""
import ast
import os
import struct
import sys
import zlib

import ohpl_game

OUT = os.path.join(ohpl_game.REPO, "soma/src/game/SomaVorbisSetups.h")


def bank_crcs(path):
    data = open(path, "rb").read()
    if data[:4] != b"FSB5":
        return
    count, headers, _, _, mode = struct.unpack_from("<5I", data, 8)
    if mode != 15:
        return
    pos = 60
    for _ in range(count):
        more = struct.unpack_from("<Q", data, pos)[0] & 1
        pos += 8
        while more:
            chunk = struct.unpack_from("<I", data, pos)[0]
            pos += 4
            more, size, kind = chunk & 1, (chunk >> 1) & 0xFFFFFF, chunk >> 25
            if kind == 11:
                yield struct.unpack_from("<I", data, pos)[0]
            pos += size


table = {}
for node in ast.parse(open(sys.argv[1]).read()).body:
    if isinstance(node, ast.Assign) and isinstance(node.value, ast.Dict):
        table.update(ast.literal_eval(node.value))
assert all(zlib.crc32(v) == k for k, v in table.items())

used = set()
for name in ("soma", "rebirth", "bunker"):
    for d, _, files in os.walk(ohpl_game.game(name).root):
        for f in files:
            if f.lower().endswith(".fsb"):
                used.update(bank_crcs(os.path.join(d, f)))
missing = sorted(used - set(table))
if missing:
    print("no setup for", " ".join(f"{c:08x}" for c in missing), file=sys.stderr)

with open(OUT, "w") as out:
    out.write("""// FMOD FSB5 Vorbis setup packets by crc32, from python-fsb5's fsb5/vorbis_headers.py
// (MIT, Copyright (c) 2016 Simon Pinfold) - generic FMOD presets, not game content.
// Generated by scripts/soma-gen-vorbis-setups.py: the presets SOMA, Rebirth and Bunker banks use.

#ifndef SOMA_VORBIS_SETUPS_H
#define SOMA_VORBIS_SETUPS_H

struct cVorbisSetup
{
	unsigned int mlCrc;
	int mlBlockShort, mlBlockLong;
	int mlSize;
	const unsigned char *mpData;
};

static const cVorbisSetup kVorbisSetups[] = {
""")
    for crc in sorted(used & set(table)):
        body = "".join(f"\\x{b:02x}" for b in table[crc])
        out.write(f'\t{{0x{crc:08x}u, 256, 2048, {len(table[crc])}, (const unsigned char *)"{body}"}},\n')
    out.write("};\n\n#endif // SOMA_VORBIS_SETUPS_H\n")
print(f"{len(used & set(table))} setups -> {OUT}")
