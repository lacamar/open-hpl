#!/usr/bin/env python3
"""Regenerate the A1 script-API layer from amnesia/src/game/LuxScriptHandler.cpp.

Outputs: rust/src/luxscript/a1_gen.rs, amnesia/src/game/LuxScriptA1Host.cpp,
rust/tests/golden/A1/decls.txt. Run from the repo root; commit the results.
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "amnesia/src/game/LuxScriptHandler.cpp"
raw = SRC.read_text(encoding="latin-1")
rawlines = raw.split("\n")
clean = re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", "", m.group(0)), raw, flags=re.S)
lines = clean.split("\n")

# Hand-written Rust natives (a1_native.rs): pure functions with a Rust implementation already.
NATIVE_HAND = {
    "ScriptSin", "ScriptCos", "ScriptTan", "ScriptAsin", "ScriptAcos", "ScriptAtan", "ScriptAtan2",
    "ScriptSqrt", "ScriptPow", "ScriptMin", "ScriptMax", "ScriptClamp", "ScriptAbs",
    "ScriptStringToInt", "ScriptStringToFloat", "ScriptStringToBool", "StringContains",
}

adds = []
for i, l in enumerate(lines):
    m = re.match(r'\s*AddFunc\("(.*)"\s*,\s*\(void \*\)(\w+)\);', l)
    if m:
        adds.append((m.group(1), m.group(2), i))

defs = {}
i = 0
while i < len(lines):
    m = re.match(r"^(.*?)__stdcall\s+cLuxScriptHandler::(\w+)\s*\(", lines[i])
    if m:
        k = i
        while lines[k].strip() != "{":
            k += 1
        e = k
        while lines[e] != "}":
            e += 1
        sig = " ".join(lines[i:k])
        sm = re.match(r"^(.*?)__stdcall\s+cLuxScriptHandler::(\w+)\s*\((.*)\)\s*$", sig)
        defs[m.group(2)] = dict(start=i, open=k, end=e, ret=sm.group(1).strip(), params=sm.group(3),
                                body=rawlines[k + 1:e])
        i = e
    i += 1

KIND = {"const string &in": "s", "float": "f", "int": "i", "bool": "b"}
RET = {"void": "v", "float": "f", "int": "i", "bool": "b", "string&": "p"}


def parse_decl(decl):
    m = re.match(r"(.*?)\s+(\w+)\((.*)\)$", decl)
    ret, name, ps = m.group(1), m.group(2), m.group(3)
    kinds = ""
    for p in [x.strip() for x in ps.split(",") if x.strip()]:
        kinds += KIND[re.sub(r"\s*\w+$", "", p).strip()]
    return RET[ret], kinds


# C++ names in registration order, first appearance
order = []
for _, n, _ in adds:
    if n not in order:
        order.append(n)
for n in order:
    assert n in defs or n in ("StopPlayerSpawnPS",), n


def cpp_params(n):
    out = []
    for p in [x.strip() for x in defs[n]["params"].split(",") if x.strip()]:
        t = re.sub(r"\s*\w+$", "", p)
        out.append("s" if "string" in t else {"float": "f", "int": "i", "bool": "b"}[t])
    return "".join(out)


for _, n, _ in adds:
    pass
for decl, n, _ in adds:
    r, k = parse_decl(decl)
    assert cpp_params(n) == k or decl.startswith("void StopPlayerSpawnPS"), (n, k, cpp_params(n))
    assert r == "v" or RET[defs[n]["ret"]] == r, n

# Stubs: one Warning(...) statement
STUB_RE = re.compile(r'^Warning\("(.*?)"((?:\s*,\s*[^,]+?)*)\);$')
stubs = {}
for n in order:
    b = [x.strip() for x in defs[n]["body"] if x.strip()]
    if len(b) == 1 and b[0].startswith("Warning(") and defs[n]["ret"] == "void":
        m = STUB_RE.match(b[0])
        assert m, b[0]
        args = [a.strip() for a in m.group(2).split(",") if a.strip()]
        stubs[n] = (m.group(1), args)

native = NATIVE_HAND | set(stubs)
host_ops = [n for n in order if n not in native]
op_of = {n: i for i, n in enumerate(host_ops)}


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


# ---------------------------------------------------------------- decls golden
dec = ROOT / "rust/tests/golden/A1"
dec.mkdir(parents=True, exist_ok=True)
(dec / "decls.txt").write_text("".join(f"{d} -> {n}\n" for d, n, _ in adds))

# ---------------------------------------------------------------- Rust
RUST_ARG = {"s": "*const c_void", "f": "f32", "i": "i32", "b": "bool"}
RUST_RET = {"v": "", "f": " -> f32", "i": " -> i32", "b": " -> bool", "p": " -> *const c_void"}
PACK = {"s": "str_arg(a{i})", "f": "Arg::f(a{i})", "i": "Arg::i(a{i})", "b": "Arg::b(a{i})"}
UNPACK = {"f": "f32", "i": "i32", "b": "bool"}

rs = ["// Generated by scripts/a1-gen.py from LuxScriptHandler.cpp; do not edit.", "#![allow(non_snake_case)]", "",
      "use super::a1::{Arg, Func, call, fmt_f, nul_cut, raw_bytes, str_arg, warn};",
      "use super::a1_native as native;",
      "use std::ffi::c_void;", ""]
funcs = {}
for decl, n, _ in adds:
    funcs.setdefault(n, parse_decl(decl))
funcs.setdefault("StopPlayerSpawnPS", ("v", ""))

for n in order:
    r, k = funcs[n]
    if n in NATIVE_HAND:
        continue
    params = ", ".join(f"a{i}: {RUST_ARG[c]}" for i, c in enumerate(k))
    if n in stubs:
        fmt, args = stubs[n]
        names = {}
        for i, p in enumerate(x.strip() for x in defs[n]["params"].split(",") if x.strip()):
            names[re.sub(r".*[\s&*]", "", p)] = i
        body = ["    let mut m: Vec<u8> = Vec::new();"]
        ai = 0
        for part in re.split(r"(%[sdf])", fmt):
            if part in ("%s", "%d", "%f"):
                idx = names[re.sub(r"\.c_str\(\)$", "", args[ai])]
                ai += 1
                if part == "%s":
                    body.append(f"    m.extend_from_slice(nul_cut(unsafe {{ raw_bytes(a{idx}) }}));")
                elif part == "%d":
                    body.append(f"    m.extend_from_slice(i32::from(a{idx}).to_string().as_bytes());")
                else:
                    body.append(f"    m.extend_from_slice(fmt_f(a{idx}).as_bytes());")
            elif part:
                body.append(f'    m.extend_from_slice(b"{part}");')
        assert ai == len(args), n
        body.append("    warn(&m);")
        used = set(re.findall(r"\ba(\d+)\b", "\n".join(body)))
        params = ", ".join(f"{'' if str(i) in used else '_'}a{i}: {RUST_ARG[c]}" for i, c in enumerate(k))
        rs.append(f"/// # Safety\n/// String arguments are engine script strings.\nunsafe extern \"C\" fn f_{n}({params}) {{")
        rs += body
        rs.append("}\n")
        continue
    rs.append(f"/// # Safety\n/// String arguments are engine script strings.\nunsafe extern \"C\" fn f_{n}({params}){RUST_RET[r]} {{")
    packs = []
    for i, c in enumerate(k):
        packs.append(f"unsafe {{ str_arg(a{i}) }}" if c == "s" else PACK[c].format(i=i))
    rs.append(f"    let args = [{', '.join(packs)}];")
    rs.append(f"    let r = call({op_of[n]}, &args);" if r != "v" else f"    call({op_of[n]}, &args);")
    ret = {"v": "", "f": "    r.as_f()", "i": "    r.as_i()", "b": "    r.as_b()", "p": "    r.p"}[r]
    if ret:
        rs.append(ret)
    rs.append("}\n")

rs.append("/// Registration order of the C++ `InitScriptFunctions`.")
rs.append("pub fn table() -> Vec<Func> {\n    vec![")
for decl, n, _ in adds:
    r, k = parse_decl(decl)
    fp = f"native::f_{n}" if n in NATIVE_HAND else f"f_{n}"
    op = op_of.get(n, 0xFFFF_FFFF)
    rs.append(f'        Func {{ decl: "{esc(decl)}", name: "{n}", op: {op if op != 0xFFFF_FFFF else "u32::MAX"}, kinds: "{k}", ret: \'{r}\', f: {fp} as *const c_void }},')
rs.append("    ]\n}\n")

rs.append("#[cfg(test)]\npub const HOST_OPS: usize = %d;\n" % len(host_ops))
rs.append("#[cfg(test)]\npub const OP_NAMES: [&str; %d] = [%s];\n" % (len(host_ops), ", ".join(f'"{n}"' for n in host_ops)))

rs.append("/// Calls table entry `i` through its real `extern \"C\"` signature.\n/// # Safety\n/// String arguments must be test strings.\n#[cfg(test)]\npub unsafe fn invoke(i: usize, a: &[Arg]) -> Arg {\n    let z = Arg::default();\n    let g = |j: usize| a.get(j).copied().unwrap_or(z);\n    match i {")
for idx, (decl, n, _) in enumerate(adds):
    r, k = funcs[n]
    fp = f"native::f_{n}" if n in NATIVE_HAND else f"f_{n}"
    cargs = []
    for j, c in enumerate(k):
        cargs.append({"s": f"g({j}).p", "f": f"g({j}).as_f()", "i": f"g({j}).as_i()", "b": f"g({j}).as_b()"}[c])
    callx = f"{fp}({', '.join(cargs)})"
    if r == "v":
        rs.append(f"        {idx} => {{ unsafe {{ {callx} }}; z }}")
    elif r == "f":
        rs.append(f"        {idx} => Arg::f(unsafe {{ {callx} }}),")
    elif r == "i":
        rs.append(f"        {idx} => Arg::i(unsafe {{ {callx} }}),")
    elif r == "b":
        rs.append(f"        {idx} => Arg::b(unsafe {{ {callx} }}),")
    else:
        rs.append(f"        {idx} => Arg {{ p: unsafe {{ {callx} }}, ..z }},")
rs.append("        _ => z,\n    }\n}")
(ROOT / "rust/src/luxscript/a1_gen.rs").write_text("\n".join(rs) + "\n")
subprocess.run(["rustfmt", "--edition", "2024", str(ROOT / "rust/src/luxscript/a1_gen.rs")], check=True)

# ---------------------------------------------------------------- C++ dispatch
out = ["// Generated by scripts/a1-gen.py; included at the end of LuxScriptHandler.cpp.", "",
       "struct OhplA1Ops", "{"]
for n in host_ops:
    r, k = funcs[n]
    ls = []
    names = []
    for j, c in enumerate(k):
        nm = f"v{j}"
        names.append(nm)
        ls.append({"s": f"string {nm}(OhplA1Str(a[{j}]));", "f": f"float {nm} = a[{j}].F();",
                   "i": f"int {nm} = a[{j}].I();", "b": f"bool {nm} = a[{j}].B();"}[c])
    call = f"cLuxScriptHandler::{n}({', '.join(names)})"
    if r == "v":
        ls.append(call + ";")
    elif r == "f":
        ls.append(f"r->SetF({call});")
    elif r == "i":
        ls.append(f"r->SetI({call});")
    elif r == "b":
        ls.append(f"r->SetB({call});")
    else:
        ls.append(f"r->p = &{call};")
    out.append(f"\tstatic void op_{op_of[n]}(const OhplA1Arg *a, OhplA1Arg *r)\n\t{{\n\t\t" + "\n\t\t".join(ls) + "\n\t}")
out.append("};\n")
out.append("typedef void (*OhplA1Op)(const OhplA1Arg *, OhplA1Arg *);")
out.append("static const OhplA1Op gvOhplA1Ops[] =\n{")
for n in host_ops:
    out.append(f"\tOhplA1Ops::op_{op_of[n]},")
out.append("};\n")
out.append("""extern "C" void OhplA1HostCall(unsigned op, const OhplA1Arg *a, size_t n, OhplA1Arg *r)
{
	if(op == kOhplA1OpWarning)
	{
		Warning("%s", string(OhplA1Str(a[0])).c_str());
		return;
	}
	if(op < sizeof(gvOhplA1Ops) / sizeof(gvOhplA1Ops[0])) gvOhplA1Ops[op](a, r);
}""")
(ROOT / "amnesia/src/game/LuxScriptA1Ops.inc").write_text("\n".join(l.rstrip() for l in out) + "\n")
print(len(adds), "decls", len(order), "fns", len(host_ops), "forwarded to C++", len(stubs) + len(NATIVE_HAND), "Rust logic")
