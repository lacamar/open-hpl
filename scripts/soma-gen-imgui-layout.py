#!/usr/bin/env python3
# Emit SOMA's property offsets for the script structs native code reads (rust/src/somaui/s8d_layout.rs).
# Rebirth and Bunker lay these out differently; their properties are registered at SOMA's offsets.
import os, re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UI = os.path.join(REPO, "rust/src/somaui")
types = set(re.findall(r'ty: "(\w+)"', open(os.path.join(UI, "s8d_defaults.rs")).read()))
types.add("cLuxScreenTextFormatParameters")

out, cur = [], None
for l in open(os.path.join(REPO, "soma/data/script_api.txt")):
    v = l.rstrip("\n").split("\t")
    if v[0] == "O":
        cur = v[1]
    elif v[0] == "P" and cur in types:
        out.append('    ("%s", "%s", %s),' % (cur, v[1].split()[-1], v[2]))
head = ["// Generated by scripts/soma-gen-imgui-layout.py from soma/data/script_api.txt - do not edit by hand.", "",
        "/// SOMA's property offsets for the script structs native code reads: (type, property, offset).",
        "pub static LAYOUT: &[(&str, &str, i32)] = &["]
open(os.path.join(UI, "s8d_layout.rs"), "w").write("\n".join(head + out + ["];"]) + "\n")
print(len(out), "properties")
