macro_rules! ops {
    ($($n:ident),* $(,)?) => {
        #[allow(non_camel_case_types, clippy::upper_case_acronyms)]
        #[repr(u32)]
        enum Seq { $($n),* }
        $(pub const $n: u32 = Seq::$n as u32;)*
        /// Names in operation order.
        pub const NAMES: &[&str] = &[$(stringify!($n)),*];
    };
}

