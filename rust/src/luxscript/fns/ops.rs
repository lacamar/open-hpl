//! Engine host ops, numbered in declaration order; `LuxScriptHostA1.cpp` has the same list in `enum OhplA1Op`
//! (checked by `host_ops_match_cpp`).

macro_rules! ops {
    ($($name:ident,)*) => {
        #[allow(non_camel_case_types, clippy::upper_case_acronyms)]
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        #[repr(u32)]
        pub enum Op {
            $($name,)*
        }
        pub use Op::*;
        #[cfg(test)]
        pub const NAMES: &[&str] = &[$(stringify!($name)),*];
    };
}

