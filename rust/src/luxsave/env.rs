//! The C++ side of a save walk. A walker owns the order and the decisions; every engine call,
//! entity creation and plain field copy is one [`Op`] that C++ performs. `a` and `b` are indices
//! or small codes, the result is a flag, a count, an id or a code. The numbering is mirrored in
//! `RustLuxSave.h` (checked by a test).

pub trait Env {
    fn call(&mut self, op: Op, a: i32, b: i32) -> i32;

    fn c(&mut self, op: Op) -> i32 {
        self.call(op, 0, 0)
    }

    fn c1(&mut self, op: Op, a: i32) -> i32 {
        self.call(op, a, 0)
    }

    fn t(&mut self, op: Op) -> bool {
        self.call(op, 0, 0) != 0
    }

    fn t1(&mut self, op: Op, a: i32) -> bool {
        self.call(op, a, 0) != 0
    }

    fn t2(&mut self, op: Op, a: i32, b: i32) -> bool {
        self.call(op, a, b) != 0
    }
}

