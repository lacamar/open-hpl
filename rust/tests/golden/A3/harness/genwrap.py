#!/usr/bin/env python3
"""genwrap.py <outdir>: tracing wrappers for the ohpl_a3_* entry points (golden recording). Writes golden_decl.h and golden_wrap.inc."""
import sys

out = sys.argv[1]
# name, id, params [(ctype, name, kind)], ret, outs
# kind: b base, h host, i int, f float, p pointer, bl bool, v3 const cVector3f*, v2 const cVector2f*, mo float* out, bo bool* out
F = [
    ('init', 1, 'b h i', 'void'),
    ('free', 2, 'b', 'void'),
    ('enter', 3, 'b h i', 'void'),
    ('leave', 4, 'b h i', 'void'),
    ('map_leave', 5, 'b', 'void'),
    ('update', 6, 'b h f', 'void'),
    ('post_update', 7, 'b h f', 'void'),
    ('do_action', 8, 'b h i bl', 'bool'),
    ('scroll', 9, 'b h f', 'void'),
    ('on_move', 10, 'b h i f', 'bool'),
    ('add_yaw', 11, 'b h f', 'bool'),
    ('add_pitch', 12, 'b h f', 'bool'),
    ('on_run', 13, 'b h bl', 'bool'),
    ('on_crouch', 14, 'b h bl', 'bool'),
    ('on_jump', 15, 'b h bl', 'bool'),
    ('crosshair', 16, 'b h', 'int32_t'),
    ('draw', 17, 'b h p f', 'void'),
    ('draw_crosshair', 18, 'b h p v3 v2', 'bool'),
    ('save_body', 19, 'b p mo bo', 'void'),
    ('allow_buoyancy', 20, 'b h p', 'bool'),
    ('destroy_entity', 21, 'b h p', 'void'),
    ('attach_sticky', 22, 'b h p', 'void'),
    ('draw_debug', 23, 'b h p p f', 'float'),
]
CT = {'b': 'OhplA3Base *', 'h': 'const OhplA3Host *', 'i': 'int32_t', 'f': 'float', 'p': 'void *', 'bl': 'bool',
      'v3': 'const hpl::cVector3f *', 'v2': 'const hpl::cVector2f *', 'mo': 'float *', 'bo': 'bool *'}
decl = ['#pragma once', '// generated by genwrap.py']
wrap = ['// generated by genwrap.py']
for name, fid, ps, ret in F:
    kinds = ps.split()
    params = ', '.join('%s a%d' % (CT[k], i) for i, k in enumerate(kinds))
    names = ', '.join('a%d' % i for i in range(len(kinds)))
    decl.append('extern "C" %s ohpl_a3_%s_real(%s) __asm__("ohpl_a3_%s");' % (ret, name, params, name))
    decl.append('%s TR_%s(%s);' % (ret, name, params))
    decl.append('#define ohpl_a3_%s TR_%s' % (name, name))
    args, outs = [], []
    for i, k in enumerate(kinds):
        a = 'a%d' % i
        if k == 'i':
            args.append('(uint32_t)%s' % a)
        elif k == 'f':
            args.append('Bits(%s)' % a)
        elif k == 'bl':
            args.append('(uint32_t)%s' % a)
        elif k == 'p':
            args.append('GP(%s)' % a)
        elif k == 'v3':
            args += ['Bits(%s->x)' % a, 'Bits(%s->y)' % a, 'Bits(%s->z)' % a]
        elif k == 'v2':
            args += ['Bits(%s->x)' % a, 'Bits(%s->y)' % a]
        elif k == 'mo':
            args.append('Bits(*%s)' % a)
            outs.append('Bits(*%s)' % a)
        elif k == 'bo':
            args.append('(uint32_t)*%s' % a)
            outs.append('(uint32_t)*%s' % a)
    base = 'a0'
    kind_arg = 'a2' if name == 'init' else '-1'
    body = ['%s TR_%s(%s)' % (ret, name, params), '{',
            '\tGBegin(%d, %s, %s, {%s});' % (fid, base, kind_arg, ', '.join(args))]
    if ret == 'void':
        body.append('\tohpl_a3_%s_real(%s);' % (name, names))
        retv = '0'
    else:
        body.append('\t%s r = ohpl_a3_%s_real(%s);' % (ret, name, names))
        retv = 'Bits(r)' if ret == 'float' else '(uint32_t)r'
    if name == 'free':
        body.append('\tGEnd(a0, %s, {}, true);' % retv)
    else:
        body.append('\tGEnd(a0, %s, {%s}, false);' % (retv, ', '.join(outs)))
    if ret != 'void':
        body.append('\treturn r;')
    body.append('}')
    wrap += body
open(out + '/golden_decl.h', 'w').write('\n'.join(decl) + '\n')
open(out + '/golden_wrap.inc', 'w').write('\n'.join(wrap) + '\n')
