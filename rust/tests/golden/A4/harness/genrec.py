#!/usr/bin/env python3
"""genrec.py <outdir> <repo>: from RustLuxEnemyA4.h and ctx.rs generate the golden recorder (C++, outdir/rec.inc and
outdir/wrap.txt) and the cargo replay dispatch (rust/src/luxenemy/a4_replay_gen.rs)."""
import os
import re
import sys

out, W = sys.argv[1], sys.argv[2]
hdr = open(W + '/amnesia/src/game/RustLuxEnemyA4.h').read()
ctxrs = open(W + '/rust/src/luxenemy/ctx.rs').read()

blk = hdr[hdr.index('extern "C" {'):]
decls = []
for m in re.finditer(r'^([\w\s\*]+?)\s*\b(ohpl_a4_\w+)\(([^)]*)\);', blk, re.M):
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    if name == 'ohpl_a4_init':
        continue
    ps = []
    for p in params.split(','):
        p = p.strip()
        mm = re.match(r'(.+?)(\w+)$', p)
        t, n = mm.group(1).strip(), mm.group(2)
        if t.endswith('*') is False and ' ' in t.strip():
            pass
        ps.append((t.replace(' *', '*').strip(), n))
    decls.append((ret, name, ps))

fields = [m.groups() for m in (re.match(r'\s*pub (\w+): P<(.+)>,$', l) for l in ctxrs.split('\n')) if m]
VEC3 = {'pf_goal', 'last_known', 'temp_pos', 'start_position'}
sizes = []
for n, t in fields:
    if t == 'Queue':
        sizes.append(0)
    elif n in VEC3:
        sizes.append(12)
    elif t in ('i32', 'f32'):
        sizes.append(4)
    elif t == 'bool':
        sizes.append(1)
    elif t == 'MoverState':
        sizes.append(32)
    elif t == 'PfWin':
        sizes.append(612)
    elif t == '[[f32; 2]; 2]':
        sizes.append(16)
    else:
        raise SystemExit('unknown ctx type ' + t)

CPP = r'''// generated by genrec.py: golden recorder for the A4 entries (RECORD builds only)
#include <unordered_map>
static const int kCtxSizes[] = {%(sizes)s};
static const int kCtxN = %(nfields)d;
static const int kLimit = %(limit)s;
static FILE *gRecF;
static int gRecCount[%(nids)d];
static uint64_t gRecTotal;
struct RecSnap
{
	std::vector<std::vector<uint8_t> > f;
	std::vector<uint8_t> base, queue;
};
struct RecEntry
{
	std::vector<uint8_t> out;
	RecSnap pre;
	std::unordered_map<void *, uint32_t> ids;
	OhplA4Base *b;
	int id;
};
static std::vector<RecEntry *> gRecStack;
static void P32(std::vector<uint8_t> &o, uint32_t v) { o.insert(o.end(), (uint8_t *)&v, (uint8_t *)&v + 4); }
static void PB(std::vector<uint8_t> &o, const void *p, size_t n) { o.insert(o.end(), (const uint8_t *)p, (const uint8_t *)p + n); }
static uint32_t PId(RecEntry *e, void *p)
{
	if(!p) return 0;
	std::unordered_map<void *, uint32_t>::iterator it = e->ids.find(p);
	if(it != e->ids.end()) return it->second;
	uint32_t id = (uint32_t)e->ids.size() + 1;
	e->ids[p] = id;
	return id;
}
static void NormBase(RecEntry *e, const OhplA4Base *b, uint8_t *dst)
{
	memcpy(dst, b, sizeof(OhplA4Base));
	uint64_t z = 0, a = PId(e, b->curAnim), s = PId(e, b->curSound);
	memcpy(dst, &z, 8);
	memcpy(dst + 8, &a, 8);
	memcpy(dst + 16, &s, 8);
}
static void Take(RecEntry *e, RecSnap &s)
{
	OhplGa3Ctx *c = e->b->c;
	void **pp = (void **)c;
	s.f.assign(kCtxN, std::vector<uint8_t>());
	for(int i = 1; i < kCtxN; ++i)
	{
		if(pp[i]) PB(s.f[i], pp[i], kCtxSizes[i]);
		else s.f[i].assign(kCtxSizes[i], 0);
	}
	s.base.assign(sizeof(OhplA4Base), 0);
	NormBase(e, e->b, &s.base[0]);
	s.queue.clear();
	for(size_t i = 0; i < ohpl_ga3_queue_len(c->queue); ++i)
	{
		OhplGa3Msg m;
		ohpl_ga3_queue_get(c->queue, i, &m);
		PB(s.queue, &m, sizeof(m));
	}
}
static void PutSnap(std::vector<uint8_t> &o, const RecSnap &s)
{
	for(int i = 1; i < kCtxN; ++i) PB(o, &s.f[i][0], kCtxSizes[i]);
	PB(o, &s.base[0], s.base.size());
	P32(o, (uint32_t)(s.queue.size() / sizeof(OhplGa3Msg)));
	if(s.queue.size()) PB(o, &s.queue[0], s.queue.size());
}
static void NormIo(RecEntry *e, const OhplA4Io *io, OhplA4Io *dst, bool ga3)
{
	*dst = *io;
	for(int k = 0; k < 3; ++k) dst->p[k] = (void *)(uintptr_t)((ga3 && k == 0) ? 0 : PId(e, io->p[k]));
}
struct RecHost
{
	const OhplA4Host *orig;
	RecEntry *e;
};
static int RecCall(void *ctx, uint32_t op, OhplA4Io *io)
{
	RecHost *rh = (RecHost *)ctx;
	RecEntry *e = rh->e;
	bool ga3 = op == 1;
	RecSnap s0, s1;
	Take(e, s0);
	OhplA4Io in;
	NormIo(e, io, &in, ga3);
	uint8_t gin[sizeof(OhplGa3Io)];
	if(ga3) memcpy(gin, io->p[0], sizeof(gin));
	int r = rh->orig->call(rh->orig->ctx, op, io);
	Take(e, s1);
	OhplA4Io outio;
	NormIo(e, io, &outio, ga3);
	P32(e->out, 1);
	P32(e->out, op);
	PB(e->out, &in, sizeof(in));
	PB(e->out, &outio, sizeof(outio));
	P32(e->out, (uint32_t)r);
	if(ga3)
	{
		PB(e->out, gin, sizeof(gin));
		PB(e->out, io->p[0], sizeof(gin));
	}
	std::vector<uint8_t> d;
	uint32_t nd = 0;
	for(int i = 1; i < kCtxN; ++i)
		if(s0.f[i] != s1.f[i])
		{
			P32(d, (uint32_t)i);
			P32(d, (uint32_t)kCtxSizes[i]);
			PB(d, &s1.f[i][0], kCtxSizes[i]);
			++nd;
		}
	if(s0.base != s1.base)
	{
		P32(d, 200);
		P32(d, (uint32_t)s1.base.size());
		PB(d, &s1.base[0], s1.base.size());
		++nd;
	}
	if(s0.queue != s1.queue)
	{
		P32(d, 201);
		P32(d, (uint32_t)s1.queue.size());
		if(s1.queue.size()) PB(d, &s1.queue[0], s1.queue.size());
		++nd;
	}
	P32(e->out, nd);
	PB(e->out, &d[0], d.size());
	return r;
}
static RecEntry *RecBegin(int id, OhplA4Base *b)
{
	RecEntry *e = new RecEntry();
	e->b = b;
	e->id = id;
	Take(e, e->pre);
	return e;
}
static void RecEnd(RecEntry *e, std::vector<uint8_t> &args, uint32_t ret, std::vector<uint8_t> &outs)
{
	if(gRecCount[e->id] < kLimit && gRecF)
	{
		++gRecCount[e->id];
		std::vector<uint8_t> o;
		P32(o, (uint32_t)e->id);
		P32(o, (uint32_t)args.size());
		if(args.size()) PB(o, &args[0], args.size());
		PutSnap(o, e->pre);
		PB(o, &e->out[0], e->out.size());
		P32(o, 0);
		P32(o, ret);
		if(outs.size()) PB(o, &outs[0], outs.size());
		RecSnap post;
		Take(e, post);
		PutSnap(o, post);
		uint32_t n = (uint32_t)o.size();
		fwrite(&n, 4, 1, gRecF);
		fwrite(&o[0], 1, o.size(), gRecF);
		++gRecTotal;
	}
	delete e;
}
extern "C" {
%(wraps)s
}
'''

RS = '''//! Generated by rust/tests/golden/A4/harness/genrec.py: calls one recorded entry with its decoded arguments.
#![allow(non_snake_case, clippy::let_and_return, clippy::needless_late_init)]
use super::a4_ffi as ffi;
use super::a4_state::{Base, Table};
use std::ffi::{c_char, c_void};

pub struct Reader<'a>(pub &'a [u8], pub usize);

impl Reader<'_> {
    pub fn u32(&mut self) -> u32 {
        let v = self.0.get(self.1..self.1 + 4).map_or(0, |b| u32::from_le_bytes([b[0], b[1], b[2], b[3]]));
        self.1 += 4;
        v
    }
    pub fn f32(&mut self) -> f32 {
        f32::from_bits(self.u32())
    }
    pub fn bytes(&mut self, n: usize) -> &[u8] {
        let s = self.0.get(self.1..self.1 + n).unwrap_or(&[]);
        self.1 += n;
        s
    }
}

pub const ENTRY_NAMES: &[&str] = &[%(names)s];
pub const CTX_SIZES: [usize; %(nfields)d] = [%(sizes)s];
pub const OUT_BYTES: &[usize] = &[%(outb)s];

/// # Safety
/// `b` points at a live `Base`; `t` at a live table.
pub unsafe fn dispatch(id: u32, r: &mut Reader, b: *mut Base, t: *const Table, outs: &mut Vec<u8>) -> u32 {
    match id {
%(arms)s
        _ => 0,
    }
}
'''

C_ARG = {'float': ('F', 'f32'), 'int32_t': ('I', 'i32'), 'bool': ('B', 'bool')}
wraps, arms, names, outb = [], [], [], []
for idx, (ret, name, ps) in enumerate(decls):
    names.append('"%s"' % name)
    has_h = len(ps) > 1 and 'OhplA4Host' in ps[1][0]
    rest = ps[(2 if has_h else 1):]
    sig = ', '.join('%s %s' % (t, n) for t, n in ps)
    enc, call_args, rs_dec, rs_call = [], [], [], []
    outs_c, outs_rs = [], []
    for t, n in rest:
        if t in C_ARG:
            k, rt = C_ARG[t]
            if k == 'F':
                enc.append('{ uint32_t u; memcpy(&u, &%s, 4); P32(args, u); }' % n)
                rs_dec.append('let a_%s = r.f32();' % n)
            elif k == 'I':
                enc.append('P32(args, (uint32_t)%s);' % n)
                rs_dec.append('let a_%s = r.u32() as i32;' % n)
            else:
                enc.append('P32(args, %s ? 1 : 0);' % n)
                rs_dec.append('let a_%s = r.u32() != 0;' % n)
            call_args.append(n)
            rs_call.append('a_' + n)
        elif t == 'const char*' or t == 'const void*':
            enc.append('P32(args, PId(e, (void *)%s));' % n)
            rs_dec.append('let a_%s = r.u32() as usize as *const %s;' % (n, 'c_char' if 'char' in t else 'c_void'))
            call_args.append(n)
            rs_call.append('a_' + n)
        elif t == 'const float*':
            enc.append('PB(args, %s, 12);' % n)
            rs_dec.append('let mut a_%s = [0f32; 3]; for v in &mut a_%s { *v = r.f32(); }' % (n, n))
            call_args.append(n)
            rs_call.append('a_' + n + '.as_ptr()')
        elif t == 'float*':
            cnt = 16 if '16' in n else 3
            outs_c.append('PB(outs, %s, %d);' % (n, cnt * 4))
            outs_rs.append(('let mut a_%s = [0f32; %d];' % (n, cnt), 'a_%s' % n))
            call_args.append(n)
            rs_call.append('a_%s.as_mut_ptr().cast()' % n if cnt == 16 else 'a_%s.as_mut_ptr()' % n)
        else:
            raise SystemExit('type ' + t)
    # C++ wrapper
    ret_c = ret
    body = ['\tRecEntry *e = RecBegin(%d, b);' % idx, '\tstd::vector<uint8_t> args, outs;']
    body += ['\t' + x for x in enc]
    if has_h:
        body += ['\tRecHost rh = {h, e};', '\tOhplA4Host nh;', '\tnh.ctx = &rh;', '\tnh.call = &RecCall;']
    real_args = ['b'] + (['&nh'] if has_h else []) + call_args
    call = '__real_%s(%s)' % (name, ', '.join(real_args))
    if ret == 'void':
        body.append('\t' + call + ';')
        rv = '0'
    elif ret == 'float':
        body.append('\tfloat r = %s;' % call)
        rv = '*(uint32_t *)&r'
    elif ret == 'bool':
        body.append('\tbool r = %s;' % call)
        rv = '(r ? 1u : 0u)'
    else:
        body.append('\t%s r = %s;' % (ret, call))
        rv = 'PId(e, r)'
    body += ['\t' + x for x in outs_c]
    body.append('\tRecEnd(e, args, %s, outs);' % rv)
    if ret != 'void':
        body.append('\treturn r;')
    wraps.append('%s __real_%s(%s);\n%s __wrap_%s(%s)\n{\n%s\n}' % (ret, name, sig, ret_c, name, sig, '\n'.join(body)))
    # Rust arm
    outb.append(sum(16 * 4 if '16' in n else 12 for t, n in rest if t == 'float*'))
    arm = ['        %d => {' % idx]
    arm += ['            ' + x for x in rs_dec]
    arm += ['            ' + a for a, _ in outs_rs]
    rcall = 'ffi::%s(b%s%s)' % (name, ', t' if has_h else '', ''.join(', ' + a for a in rs_call))
    if ret == 'void':
        arm.append('            unsafe { %s };' % rcall)
        arm.append('            let ret = 0u32;')
    elif ret == 'float':
        arm.append('            let ret = unsafe { %s }.to_bits();' % rcall)
    elif ret == 'bool':
        arm.append('            let ret = u32::from(unsafe { %s });' % rcall)
    else:
        arm.append('            let ret = unsafe { %s } as usize as u32;' % rcall)
    for _, o in outs_rs:
        arm.append('            for v in %s { outs.extend_from_slice(&v.to_bits().to_le_bytes()); }' % o)
    arm.append('            ret')
    arm.append('        }')
    arms.append('\n'.join(arm))

limit = os.environ.get('A4_REC_LIMIT', '12')
open(out + '/rec.inc', 'w').write(CPP % dict(sizes=', '.join(map(str, sizes)), nfields=len(sizes), nids=len(decls) + 1, limit=limit, wraps='\n'.join(wraps)))
open(out + '/wrap.txt', 'w').write(' '.join('-Wl,--wrap=' + d[1] for d in decls))
open(W + '/rust/src/luxenemy/a4_replay_gen.rs', 'w').write(RS % dict(names=', '.join(names), arms='\n'.join(arms), nfields=len(sizes), sizes=', '.join(map(str, sizes)), outb=', '.join(map(str, outb))))
print(len(decls), 'entries', len(sizes), 'ctx fields')
