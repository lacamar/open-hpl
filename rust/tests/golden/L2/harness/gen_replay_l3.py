#!/usr/bin/env python3
"""From RustGlRes.h generates (1) ld --wrap recorders logging every ohpl_gl{tex,vb,fb,dsb,sh,prog}_*
call the C++ shells make (plus ohpl_glctx_get_caps) and (2) the Rust dispatcher replaying such a log.

usage: gen_replay_l3.py <RustGlRes.h> <out wrap_gen.cpp> <out replay_gen.rs> <out wrap.ldflags>

Log grammar: one call per line, `name arg...`; handles are `H<n>` in creation order (`=> H<n>` binds the
result of a `new`), pointers to registered ranges are `label+offset`, strings hex, structs comma lists.
"""
import re
import sys

hdr = open(sys.argv[1]).read()
body = hdr[hdr.index('extern "C" {'):]


def split_args(args):
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


# pure queries without GL calls: neither logged nor replayed
SKIP = {"ohpl_gltex_handle", "ohpl_gltex_handle_count", "ohpl_gltex_contains_data", "ohpl_glvb_needs_compile", "ohpl_glprog_current"}
decls = []
for line in body.splitlines():
    m = re.match(r"^(.*?)(ohpl_gl(?:tex|vb|fb|dsb|sh|prog)_\w+)\((.*)\);$", line.strip())
    if m and m.group(2) not in SKIP:
        decls.append((m.group(1).strip(), m.group(2), split_args(m.group(3))))
decls.append(("int", "ohpl_glctx_get_caps", ["OhplGlCtx*", "int", "bool"]))

KIND = {
    "uint64_t": "h", "int": "int", "unsigned": "u32", "bool": "bool", "float": "f32", "size_t": "usize",
    "int64_t": "i64", "OhplGlV2": "v2", "OhplGlV3": "v3", "constchar*": "str", "OhplTexIo*": "io",
    "constOhplTexIo*": "io", "constOhplTexFace*": "faces", "constvoid*": "ptr", "constOhplVbData*": "vbdata",
    "constunsigned*": "ptru", "constvoid*const*": "ptrs", "constfloat*": "skipf", "float*": "out",
    "OhplTexRes*": "out_res", "OhplGlAttach*": "out_attach", "OhplDsbOut*": "out_dsb", "unsigned*": "out_u32",
    "size_t*": "out_len", "char(*)[128]": "out_name", "float(*)[16]": "out_vals", "OhplGlCtx*": "ctx",
}


def norm(t):
    t = re.sub(r"\(\*\w*\)", "(*)", t.strip())
    m = re.match(r"^(.*[\s*])(\w+)$", t)
    if m and m.group(1).strip() not in ("const",) and "(*)" not in t:
        t = m.group(1)
    return t.replace(" ", "")


def ctype(t):
    t = re.sub(r"\(\*\w*\)", "(*)", t.strip())
    m = re.match(r"^(.*[\s*])(\w+)$", t)
    if m and m.group(1).strip() not in ("const",) and "(*)" not in t:
        t = m.group(1).rstrip()
    return t


def kind(t):
    return KIND[norm(t)]


wrap = [
    "// generated by gen_replay_l3.py; do not edit",
    '#include "impl/RustGlRes.h"', '#include "impl/RustGlCtx.h"', '#include "fakegl.h"',
    "#include <cstdio>", "#include <cstring>", "#include <map>", "using namespace hpl;",
    "std::string gFfi;", "bool gFfiOn = false;",
    "static std::map<uint64_t, int> gH; static std::map<uint64_t, int> gVbElems; static int gHN = 0;",
    'static std::string HS(uint64_t h) { auto it = gH.find(h); return it == gH.end() ? "H?" : "H" + std::to_string(it->second); }',
    'static std::string Hex(const char *s) { if(!s) return "n"; static const char *d = "0123456789abcdef"; std::string r = "x"; for(; *s; ++s) { r += d[(unsigned char)*s >> 4]; r += d[*s & 15]; } return r; }',
    'static std::string I3(const cVector3l &v) { return std::to_string(v.x) + "," + std::to_string(v.y) + "," + std::to_string(v.z); }',
    'static std::string IoS(const OhplTexIo *o) { std::string s;'
    ' for(int v : {o->type, o->usage, o->filter, o->wrap[0], o->wrap[1], o->wrap[2], o->compareMode, o->compareFunc, o->animMode, o->pixelFormat}) s += std::to_string(v) + ",";'
    ' s += std::to_string(o->downLevel) + "," + std::to_string(o->memory) + "," + I3(o->size) + "," + I3(o->minSize) + "," + A(o->frameTime) + "," + A(o->aniso) + ","'
    ' + std::to_string(o->useMips) + "," + std::to_string(o->srgb) + "," + std::to_string(o->compressed); return s; }',
    'static std::string FacesS(const OhplTexFace *f, int n) { std::string s = "F"; for(int i = 0; i < n; ++i) { if(i) s += "^"; s += std::to_string(f[i].numMips) + ";" + I3(f[i].size) + ";" + std::to_string(f[i].format) + ";";'
    ' for(int m = 0; m < f[i].numMips; ++m) { if(m) s += "|"; s += A(f[i].levels[m].data) + "/" + std::to_string(f[i].levels[m].size); } } return s; }',
    'static std::string VbS(uint64_t h, const OhplVbData *d) { int n = gVbElems[h]; if(n == 0) return "-"; std::string s; for(int i = 0; i < n; ++i) { if(i) s += "|"; s += A(d[i].ptr) + ":" + std::to_string(d[i].bytes); } return s; }',
    'static std::string PtrsS(uint64_t h, const void *const *p) { int n = gVbElems[h]; if(!p || n == 0) return "-"; std::string s; for(int i = 0; i < n; ++i) { if(i) s += "|"; s += A(p[i]); } return s; }',
    "",
    'extern "C" {',
    "",
]
ld = []
arms = []

for ret, name, alist in decls:
    ks = [kind(a) for a in alist]
    ld.append(f"-Wl,--wrap={name}")
    params = ", ".join(ctype(a).replace("(*)", f"(*a{i})") + ("" if "(*)" in ctype(a) else f" a{i}") for i, a in enumerate(alist))
    call = ", ".join(f"a{i}" for i in range(len(alist)))
    wrap.append(f"{ret} __real_{name}({params});")
    wrap.append(f"{ret} __wrap_{name}({params})")
    wrap.append("{")
    wrap.append(f'\tstd::string s = "{name}";')
    for i, k in enumerate(ks):
        if k == "ctx":
            continue
        if k == "h": wrap.append(f'\ts += " " + HS(a{i});')
        elif k in ("int", "u32", "usize", "i64"): wrap.append(f'\ts += " " + std::to_string(a{i});')
        elif k == "bool": wrap.append(f'\ts += a{i} ? " 1" : " 0";')
        elif k == "f32": wrap.append(f'\ts += " " + A(a{i});')
        elif k == "v2": wrap.append(f'\ts += " " + std::to_string(a{i}.x) + "," + std::to_string(a{i}.y);')
        elif k == "v3": wrap.append(f'\ts += " " + std::to_string(a{i}.x) + "," + std::to_string(a{i}.y) + "," + std::to_string(a{i}.z);')
        elif k == "str": wrap.append(f'\ts += " " + Hex(a{i});')
        elif k == "io": wrap.append(f'\ts += " " + IoS(a{i});')
        elif k == "faces": wrap.append(f'\ts += " " + FacesS(a{i}, a{i + 1});')
        elif k in ("ptr", "ptru"): wrap.append(f'\ts += " " + A((const void*)a{i});')
        elif k == "vbdata": wrap.append(f'\ts += " " + VbS(a0, a{i});')
        elif k == "ptrs": wrap.append(f'\ts += " " + PtrsS(a0, a{i});')
        else: wrap.append('\ts += " -";')
    if name == "ohpl_glvb_add_element":
        wrap.append("\tgVbElems[a0]++;")
    pre = ""
    if ret == "void":
        wrap.append(f"\t__real_{name}({call});")
        wrap.append('\tif(gFfiOn) gFfi += s + "\\n";')
    else:
        wrap.append(f"\t{ret} r = __real_{name}({call});")
        if ret == "uint64_t":
            wrap.append('\tgH[r] = ++gHN;')
            wrap.append('\tif(gFfiOn) gFfi += s + " => " + HS(r) + "\\n";')
        else:
            wrap.append('\tif(gFfiOn) gFfi += s + "\\n";')
        wrap.append("\treturn r;")
    wrap.append("}")
    wrap.append("")

    # Rust arm
    parts, pre, ti = [], [], 0
    for i, k in enumerate(ks):
        if k == "ctx":
            parts.append("&mut *r.ctx()")
            continue
        if k in ("out", "out_res", "out_attach", "out_dsb", "out_u32", "out_len", "out_name", "out_vals", "skipf"):
            ti += 1
            if k == "out":
                pre.append(f"let mut o{i} = vec![0f32; 1 << 18];")
                parts.append(f"o{i}.as_mut_ptr()")
            elif k == "out_res":
                pre.append(f"let mut o{i} = Res::default();")
                parts.append(f"&mut o{i}")
            elif k == "out_attach":
                pre.append(f"let mut o{i} = Attach::default();")
                parts.append(f"&mut o{i}")
            elif k == "out_dsb":
                pre.append(f"let mut o{i} = ffi::DsbOut {{ id: 0, kind: 0 }};")
                parts.append(f"&mut o{i}")
            elif k == "out_u32":
                pre.append(f"let mut o{i} = 0u32;")
                parts.append(f"&mut o{i}")
            elif k == "out_len":
                pre.append(f"let mut o{i} = 0usize;")
                parts.append(f"&mut o{i}")
            elif k == "out_name":
                pre.append(f"let mut o{i} = [0u8; 128];")
                parts.append(f"&mut o{i}")
            elif k == "out_vals":
                pre.append(f"let mut o{i} = [0f32; 16];")
                parts.append(f"&mut o{i}")
            else:
                pre.append(f"let o{i} = vec![0f32; 256];")
                parts.append(f"o{i}.as_ptr()")
            continue
        tok = f"t[{ti}]"
        ti += 1
        if k == "h": parts.append(f"r.handle({tok})")
        elif k == "int": parts.append(f"{tok}.parse::<i32>().unwrap_or(0)")
        elif k == "u32": parts.append(f"{tok}.parse::<u32>().unwrap_or(0)")
        elif k == "usize": parts.append(f"{tok}.parse::<usize>().unwrap_or(0)")
        elif k == "i64": parts.append(f"{tok}.parse::<i64>().unwrap_or(0)")
        elif k == "bool": parts.append(f'{tok} == "1"')
        elif k == "f32": parts.append(f"fl({tok})")
        elif k == "v2": parts.append(f"v2({tok})")
        elif k == "v3": parts.append(f"v3({tok})")
        elif k == "str":
            pre.append(f"let s{i} = cstr({tok});")
            parts.append(f"s{i}.as_ptr().cast()")
        elif k == "io":
            pre.append(f"let mut io{i} = io({tok});")
            parts.append(f"&mut io{i}")
        elif k == "faces":
            pre.append(f"let (_lv{i}, f{i}) = r.faces({tok});")
            parts.append(f"f{i}.as_ptr()")
        elif k == "ptr": parts.append(f"r.ptr({tok})")
        elif k == "ptru": parts.append(f"r.ptr({tok}).cast()")
        elif k == "vbdata":
            pre.append(f"let d{i} = r.vbdata({tok});")
            parts.append(f"d{i}.as_ptr()")
        elif k == "ptrs":
            pre.append(f"let pp{i} = r.ptrs({tok});")
            parts.append(f"if {tok} == \"-\" {{ core::ptr::null() }} else {{ pp{i}.as_ptr() }}")
    arg_list = ", ".join(parts)
    stmts = " ".join(pre)
    fn = f"ffi::{name}"
    if name == "ohpl_glctx_get_caps":
        arms.append(f'        "{name}" => {{ {stmts} let _ = r.ctx().get_caps(t[0].parse::<i32>().unwrap_or(0), t[1] == "1"); }}')
        continue
    call_expr = f"unsafe {{ {fn}({arg_list}) }}" if ret == "void" or any(k in ("io", "faces", "ptr", "ptru", "vbdata", "ptrs", "str", "out", "out_res", "out_attach", "out_dsb", "out_u32", "out_len", "out_name", "out_vals", "skipf") for k in ks) or name.endswith("_new") else f"{fn}({arg_list})"
    if ret == "uint64_t":
        arms.append(f'        "{name}" => {{ {stmts} let v = {call_expr}; bind = Some(v); }}')
    else:
        arms.append(f'        "{name}" => {{ {stmts} let _ = {call_expr}; }}')

wrap.append("}")
open(sys.argv[2], "w").write("\n".join(wrap) + "\n")
open(sys.argv[4], "w").write(" ".join(ld) + "\n")
rs = [
    "// generated by gen_replay_l3.py; do not edit",
    "#![allow(clippy::unnecessary_mut_passed, unused_unsafe, clippy::let_unit_value, clippy::useless_conversion, unused_mut)]",
    "use super::replay::*;",
    "use crate::backend::gl_res::ffi;",
    "use crate::backend::gl_res::tex::Res;",
    "use crate::gl::fbo::Attach;",
    "",
    "/// Runs one logged call; returns the value a `new` produced.",
    "pub fn dispatch(r: &mut Replay, name: &str, t: &[&str]) -> Option<Option<u64>> {",
    "    let mut bind: Option<u64> = None;",
    "    match name {",
] + arms + [
    "        _ => return None,",
    "    }",
    "    Some(bind)",
    "}",
]
open(sys.argv[3], "w").write("\n".join(rs) + "\n")
print(len(decls), "wrapped")
