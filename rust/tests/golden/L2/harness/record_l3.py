#!/usr/bin/env python3
"""usage: record_l3.py <out dir after compare_l3.sh> <script dir> <golden dir> <gl_res tests dir>

Golden trace = the GL calls of the C++ path trace (value lines such as ret= are compared by
compare_l3.sh only); golden ffi = the shell-to-Rust call log of the Rust path. Also writes the script
copies and the test list included by src/backend/gl_res/tests.rs.
"""
import glob
import os
import re
import shutil
import sys

out, scripts, gold, tests = sys.argv[1:5]
os.makedirs(gold, exist_ok=True)
os.makedirs(f"{gold}/scripts", exist_ok=True)
for old in glob.glob(f"{gold}/trace_*.txt") + glob.glob(f"{gold}/ffi_*.txt") + glob.glob(f"{gold}/scripts/*.txt"):
    os.remove(old)
GL = re.compile(r"^glu?[A-Z]\w*\(")
entries, total = [], 0
for cpp in sorted(glob.glob(f"{out}/*.cpp.txt")):
    base = os.path.basename(cpp)[: -len(".cpp.txt")]
    name, ext = base.rsplit("_", 1)
    lines = [l for l in open(cpp).read().splitlines() if GL.match(l)]
    open(f"{gold}/trace_{base}.txt", "w").write("\n".join(lines) + "\n")
    shutil.copy(f"{out}/{base}.rust.ffi", f"{gold}/ffi_{base}.txt")
    if not os.path.exists(f"{gold}/scripts/{name}.txt"):
        shutil.copy(f"{scripts}/{name}.txt", f"{gold}/scripts/{name}.txt")
    entries.append((base, ext))
    total += len(lines)
with open(f"{tests}/golden_list.rs", "w") as f:
    f.write("// generated by record_l3.py; do not edit\ngolden! {\n")
    for base, ext in entries:
        f.write(f'    replay_{base.lower()}: "{ext}" "{base}";\n')
    f.write("}\n")
print(len(entries), "recordings,", total, "golden trace lines")
