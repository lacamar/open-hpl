#!/usr/bin/env python3
"""From RustGlCtx.h generates (1) ld --wrap recorders that log every ohpl_glctx_* / ohpl_glq_* call
the C++ shell makes, and (2) the Rust dispatcher that replays such a log through the ffi.

usage: gen_replay.py <RustGlCtx.h> <out wrap_gen.cpp> <out replay.rs> <out wrap.ldflags>
"""
import re
import sys

hdr = open(sys.argv[1]).read()
body = hdr[hdr.index('extern "C" {'):]
decls = []

def split_args(args):
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out

for line in body.splitlines():
    m = re.match(r"^(.+?)\s*(ohpl_gl(?:ctx|q)_\w+)\((.*)\);$", line.strip())
    if m:
        decls.append((m.group(1).strip(), m.group(2), split_args(m.group(3))))

SKIP = {"ohpl_glctx_set_host_log", "ohpl_glctx_caps_line", "ohpl_glctx_window"}

def kind(t):
    t = t.replace(" ", "")
    return {
        "OhplGlCtx*": "ctx", "bool": "bool", "int": "int", "unsigned": "u32", "float": "f32",
        "OhplGlV2": "v2", "OhplGlV2*": "out", "constchar*": "str", "constint*": "ints",
        "constfloat*": "ptr", "constvoid*": "ptr", "void*": "ptr", "float*const*": "ptr",
        "int(*)[4]": "out", "constint(*)[4]": "arr4", "constint(*)[6]": "arr6",
        "constfloat(*)[16]": "arr16", "OhplGlCtxCfg*": "cfg", "OhplGlQuery*": "query",
        "constOhplGlQuery*": "query", "constunsignedchar*": "ptr",
    }[t]

wrap = ['// generated by gen_replay.py; do not edit', '#include "impl/RustGlCtx.h"', '#include "fakegl.h"',
        '#include <cstdio>', '#include <cstring>', 'using namespace hpl;', 'std::string gFfi;',
        'static std::string H(float v) { return A(v); }', 'static std::string V(OhplGlV2 v) { return std::to_string(v.x) + "," + std::to_string(v.y); }',
        'static std::string P(const void *p) { return A(p); }', 'extern "C" {']
ld = []
rs = []
arms = []
for ret, name, alist in decls:
    if name in SKIP:
        continue
    ks = [kind(a) for a in alist]
    ld.append(f"-Wl,--wrap={name}")
    params = ", ".join(f"{a} a{i}" if "(*)" not in a else a.replace("(*)", f"(*a{i})") for i, a in enumerate(alist))
    call = ", ".join(f"a{i}" for i in range(len(alist)))
    wrap.append(f"{ret} __real_{name}({params});")
    wrap.append(f"{ret} __wrap_{name}({params})")
    wrap.append("{")
    wrap.append(f'\tstd::string s = "{name}";')
    for i, k in enumerate(ks):
        if k == "ctx": continue
        if k == "bool": wrap.append(f'\ts += a{i} ? " 1" : " 0";')
        elif k == "int": wrap.append(f'\ts += " " + std::to_string(a{i});')
        elif k == "u32": wrap.append(f'\ts += " " + std::to_string(a{i});')
        elif k == "f32": wrap.append(f'\ts += " " + H(a{i});')
        elif k == "v2": wrap.append(f'\ts += " " + V(a{i});')
        elif k == "out": wrap.append('\ts += " -";')
        elif k == "str": wrap.append(f'\ts += std::string(" s:") + a{i};')
        elif k == "ints":
            wrap.append(f'\ts += " ["; for(int i = 0; i < a{i+1}; ++i) {{ if(i) s += ";"; s += std::to_string(a{i}[i]); }} s += "]";')
        elif k == "ptr": wrap.append(f'\ts += " " + P(a{i});')
        elif k == "arr4": wrap.append(f'\ts += " ["; for(int i = 0; i < 4; ++i) {{ if(i) s += ";"; s += std::to_string((*a{i})[i]); }} s += "]";')
        elif k == "arr6": wrap.append(f'\ts += " ["; for(int i = 0; i < 6; ++i) {{ if(i) s += ";"; s += std::to_string((*a{i})[i]); }} s += "]";')
        elif k == "arr16": wrap.append(f'\ts += " ["; for(int i = 0; i < 16; ++i) {{ if(i) s += ";"; s += H((*a{i})[i]); }} s += "]";')
        elif k == "cfg":
            wrap.append(f'\ts += " " + std::to_string(a{i}->width) + "," + std::to_string(a{i}->height) + "," + std::to_string(a{i}->display) + "," + std::to_string(a{i}->bpp) + "," + std::to_string(a{i}->fullscreen) + "," + std::to_string(a{i}->multisampling) + "," + std::to_string(a{i}->headless) + ",s:" + a{i}->caption;')
        elif k == "query": wrap.append('\ts += " -";')
    wrap.append("\tgFfi += s + \"\\n\";")
    wrap.append('\tgTrace += "<\\n";')
    if ret == 'void':
        wrap.append(f"\t__real_{name}({call});")
        wrap.append('\tgTrace += ">\\n";')
    else:
        wrap.append(f"\t{ret} r = __real_{name}({call});")
        wrap.append('\tgTrace += ">\\n";')
        wrap.append("\treturn r;")
    wrap.append("}")
    wrap.append("")

    # Rust arm
    rfn = f"ffi::{name}"
    parts = []
    pre = []
    ti = 0
    for i, k in enumerate(ks):
        if k == "ctx":
            parts.append("c")
            continue
        tok = f"t[{ti}]"
        ti += 1
        if k == "bool": parts.append(f"{tok} == \"1\"")
        elif k == "int": parts.append(f"{tok}.parse::<i32>().unwrap_or(0)")
        elif k == "u32": parts.append(f"{tok}.parse::<u32>().unwrap_or(0)")
        elif k == "f32": parts.append(f"fl({tok})")
        elif k == "v2": parts.append(f"v2({tok})")
        elif k == "out":
            if alist[i].replace(" ", "") == "OhplGlV2*":
                pre.append("let mut o2 = Vector2l { x: 0, y: 0 };")
                parts.append("&mut o2")
            else:
                pre.append("let mut o4 = [0i32; 4];")
                parts.append("&mut o4")
        elif k == "str":
            pre.append(f"let s{i} = CString::new({tok}.strip_prefix(\"s:\").unwrap_or(\"\")).unwrap_or_default();")
            parts.append(f"s{i}.as_ptr()")
        elif k == "ints":
            pre.append(f"let l{i} = list::<i32>({tok});")
            parts.append(f"l{i}.as_ptr()")
        elif k == "ptr":
            parts.append({"constfloat*": "r.p_f32", "constvoid*": "r.p_cvoid", "void*": "r.p_mvoid",
                          "float*const*": "r.p_tcs"}[alist[i].replace(" ", "")] + f"({tok})")
        elif k == "arr4":
            pre.append(f"let l{i}: [i32; 4] = arr({tok});")
            parts.append(f"&l{i}")
        elif k == "arr6":
            pre.append(f"let l{i}: [i32; 6] = arr({tok});")
            parts.append(f"&l{i}")
        elif k == "arr16":
            pre.append(f"let l{i}: [f32; 16] = farr({tok});")
            parts.append(f"&l{i}")
        elif k == "cfg":
            pre.append(f"let (mut cfg, _cap) = r.cfg({tok});")
            parts.append("&mut cfg")
        elif k == "query": parts.append("&mut r.query")
    arg_list = ", ".join(parts)
    stmts = " ".join(pre)
    q = "q" if False else ""
    if name == "ohpl_glctx_new":
        arms.append('        "ohpl_glctx_new" => { r.ctx = ffi::ohpl_glctx_new(); }')
    elif name == "ohpl_glctx_free":
        arms.append('        "ohpl_glctx_free" => { unsafe { ffi::ohpl_glctx_free(c) }; r.ctx = std::ptr::null_mut(); }')
    else:
        let_ = "" if ret == "void" else "let _ = "
        arms.append(f'        "{name}" => {{ {stmts} {let_}unsafe {{ {rfn}({arg_list}) }}; }}')

wrap.append("}")
open(sys.argv[2], "w").write("\n".join(wrap) + "\n")
open(sys.argv[4], "w").write(" ".join(ld) + "\n")
rs.append("// generated by gen_replay.py; do not edit")
rs.append("#![allow(clippy::unnecessary_mut_passed)]")
rs.append("use super::replay::*;")
rs.append("use crate::backend::gl_ctx::ffi;")
rs.append("use crate::types::Vector2l;")
rs.append("use std::ffi::CString;")
rs.append("")
rs.append("pub fn dispatch(r: &mut Replay, name: &str, t: &[&str]) -> bool {")
rs.append("    let c = r.ctx;")
rs.append("    match name {")
rs += arms
rs.append("        _ => return false,")
rs.append("    }")
rs.append("    true")
rs.append("}")
open(sys.argv[3], "w").write("\n".join(rs) + "\n")
print(len(decls) - len(SKIP), "wrapped")
